const MEDIA_TYPES: Readonly<Record<string, string>> = {
  ".avif": "image/avif",
  ".bmp": "image/bmp",
  ".gif": "image/gif",
  ".heic": "image/heic",
  ".heif": "image/heif",
  ".jpeg": "image/jpeg",
  ".jpg": "image/jpeg",
  ".markdown": "text/markdown",
  ".md": "text/markdown",
  ".png": "image/png",
  ".tif": "image/tiff",
  ".tiff": "image/tiff",
  ".webp": "image/webp",
  ".m4v": "video/mp4",
  ".mov": "video/quicktime",
  ".mp4": "video/mp4",
  ".webm": "video/webm",
};

export const mediaTypeOf = (name: string): string | undefined => {
  const dot = name.lastIndexOf(".");
  return dot < 0 ? undefined : MEDIA_TYPES[name.slice(dot).toLowerCase()];
};
